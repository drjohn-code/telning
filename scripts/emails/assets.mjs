// Images the emails need, as PNG/JPG (many email apps cannot show SVG, WebP or AVIF): the logo lockup from the site
// header, a folk picture or two, and one square thumbnail per product for the order emails. Writes public/email/ and
// server/emails/thumbs.js (the SKUs that have a thumbnail). Run after product photos change: npm run emails:assets
import sharp from 'sharp';
import { fileURLToPath } from 'node:url';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { catalog } from '../../server/catalog-data.js';

const root = new URL('../../', import.meta.url);
const out = new URL('public/email/', root);
mkdirSync(new URL('products/', out), { recursive: true });
const PAPER = { r: 0xf6, g: 0xf1, b: 0xe8 };

// 1. the logo lockup, exactly as the site header draws it, 3× the 170 px it is shown at
const header = readFileSync(new URL('src/components/Header.astro', root), 'utf8');
const svg = header.match(/<svg class="tn-lockup"[\s\S]*?<\/svg>/)[0]
  .replace(' class="tn-lockup"', ' xmlns="http://www.w3.org/2000/svg"').replace(/ aria-hidden="true"| focusable="false"/g, '')
  .replace(/var\(--red\)/g, '#ce4029').replace(/var\(--cream\)/g, '#fffdf8').replace(/var\(--ink\)/g, '#16140f');
await sharp(Buffer.from(svg), { density: 300 }).resize({ width: 510 }).png({ compressionLevel: 9 }).toFile(fileURLToPath(new URL('telning-logo.png', out)));
// the header band of every email: the logo on a paper-coloured block (24 px left padding, square corners, shown at 1/3
// of these pixels) plus paper.png, stretched over the rest of the width, so the band is as wide as the cream card
// below. Both are pictures: dark-mode email apps darken the page but never pictures, so the black words stay
// readable; in light mode the band melts into the paper background. (A new file name: Gmail's image proxy keeps
// old pictures under the same address.)
const lw = 510, lh = Math.round((130 / 471.2) * lw), padX = 72, padY = 42;
const block = `<svg xmlns="http://www.w3.org/2000/svg" width="${lw + 2 * padX}" height="${lh + 2 * padY}"><rect width="100%" height="100%" fill="#f6f1e8"/></svg>`;
const logoPng = await sharp(Buffer.from(svg), { density: 300 }).resize({ width: lw }).png().toBuffer();
await sharp(Buffer.from(block)).composite([{ input: logoPng, left: padX, top: padY }]).flatten({ background: PAPER }).png({ compressionLevel: 9 }).toFile(fileURLToPath(new URL('telning-logo-badge.png', out)));
await sharp({ create: { width: 8, height: 8, channels: 3, background: PAPER } }).png().toFile(fileURLToPath(new URL('paper.png', out)));

// 2. folk pictures (the site's cut-outs), 2× their email size
for (const name of ['gift', 'plane', 'mailbox']) {
  await sharp(fileURLToPath(new URL(`public/art/folk/${name}-480.webp`, root))).resize({ width: 280 }).png({ compressionLevel: 9 }).toFile(fileURLToPath(new URL(`${name}.png`, out)));
}

// 3. one square thumbnail per product: its first photo, 2× the 72 px it is shown at
const skus = [];
for (const p of catalog.bySku.values()) {
  const base = p.images?.[0]?.src;
  const file = base && ['-600.webp', '-1200.webp', '.webp'].map((x) => new URL(`public${base}${x}`, root)).find((u) => existsSync(u));
  if (!file) continue;
  await sharp(fileURLToPath(file)).resize(160, 160, { fit: 'cover' }).flatten({ background: PAPER }).jpeg({ quality: 80, mozjpeg: true }).toFile(fileURLToPath(new URL(`products/${p.sku}.jpg`, out)));
  skus.push(p.sku);
}
writeFileSync(new URL('server/emails/thumbs.js', root), `// Generated by scripts/emails/assets.mjs. The products with a thumbnail at https://telning.com/email/products/<sku>.jpg\nexport const THUMBS = new Set(${JSON.stringify(skus.sort())});\n`);
console.log(`email assets: logo, 3 folk pictures, ${skus.length} product thumbnails`);
