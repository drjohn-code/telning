// Compile every MJML email template to server/emails/compiled/<name>.html (committed; the Vercel functions read them at
// runtime without MJML). Run after changing emails/: node scripts/emails/build.mjs
import mjml2html from 'mjml';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { TEMPLATES } from '../../emails/templates.mjs';

const OUT = new URL('../../server/emails/compiled/', import.meta.url);
mkdirSync(OUT, { recursive: true });
const index = {};
for (const [name, t] of Object.entries(TEMPLATES)) {
  const { html, errors } = await mjml2html(t.build(), { validationLevel: "soft", minify: false });
  if ((errors || []).length) console.warn(name, errors.map((e) => e.formattedMessage).join('\n'));
  writeFileSync(new URL(`${name}.html`, OUT), html);
  index[name] = { subject: t.subject, kind: t.kind };
}
writeFileSync(new URL('index.json', OUT), JSON.stringify(index, null, 2));
// one ES module with every template inside, so the Vercel functions and the Astro build import it without file reads
const mod = Object.entries(TEMPLATES).map(([name, t]) => `  ${JSON.stringify(name)}: { subject: ${JSON.stringify(t.subject)}, kind: ${JSON.stringify(t.kind)}, html: ${JSON.stringify(readFileSync(new URL(`${name}.html`, OUT), 'utf8'))} },`).join('\n');
writeFileSync(new URL('../compiled.js', OUT), `// Generated by scripts/emails/build.mjs from emails/templates.mjs. Do not edit by hand.\nexport const COMPILED = {\n${mod}\n};\n`);
console.log(`emails: ${Object.keys(index).length} templates compiled`);
